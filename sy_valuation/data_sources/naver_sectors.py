def sector_from_naver(industry_code: str | int | None) -> str:
    """Naver industryCode → 섹터 라벨. 매핑이 없으면 "" (호출측이 "기타" 유지)."""
    if industry_code in (None, ""):
        return ""
    return NAVER_INDUSTRY_TO_SECTOR.get(str(industry_code).strip(), "")
